#!/usr/bin/env python3
"""Prepare or verify a local release candidate from already-built artifacts.

The version comes from the project's dynamic version source. Draft mode permits
a pending license decision; release mode runs check_release's required-license
checks. Neither mode builds, uploads, commits, or tags anything.
"""
from __future__ import annotations

import argparse
import configparser
from email.parser import Parser
import hashlib
import importlib.util
import json
from pathlib import Path, PurePosixPath
import shutil
import tarfile
import tempfile
from typing import Any
import zipfile


_SPEC = importlib.util.spec_from_file_location("_rope_bundle_release_check", Path(__file__).with_name("check_release.py"))
assert _SPEC is not None and _SPEC.loader is not None
check_release = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(check_release)

SCHEMA = "rope-profiler.release.v1"
_PUBLIC_DIRECTORIES = ("docs", "tools", ".github", "examples", "benchmarks", "tests", "research_tools")
_IGNORED_PARTS = {"__pycache__", ".pytest_cache", ".DS_Store"}


class ReleaseBundleError(ValueError):
    """The artifacts, source checkout, or candidate directory disagree."""


def _sha_file(path: Path) -> dict[str, Any]:
    digest = hashlib.sha256()
    size = 0
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
            size += len(block)
    return {"sha256": digest.hexdigest(), "size": size}


def _sha_bytes(content: bytes) -> dict[str, Any]:
    return {"sha256": hashlib.sha256(content).hexdigest(), "size": len(content)}


def _authored(path: PurePosixPath) -> bool:
    return not set(path.parts).intersection(_IGNORED_PARTS) and path.suffix not in {".pyc", ".pyo"}


def _safe_member(name: str) -> PurePosixPath:
    path = PurePosixPath(name)
    if path.is_absolute() or ".." in path.parts or not path.parts or "\\" in name:
        raise ReleaseBundleError(f"artifact contains an unsafe member path: {name}")
    return path


def _required_inputs(root: Path) -> set[str]:
    config = check_release.tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
    project = config["project"]
    readme = project["readme"]
    readme_path = readme if isinstance(readme, str) else readme["file"]
    required = {"pyproject.toml", str(_safe_member(readme_path))}
    for filename in ("MANIFEST.in", "setup.py", "setup.cfg", "CHANGELOG.md", "CONTRIBUTING.md", "CITATION.cff"):
        if (root / filename).is_file():
            required.add(filename)
    for pattern in project.get("license-files", ["LICENSE*", "LICENCE*", "COPYING*", "NOTICE*", "AUTHORS*"]):
        _safe_member(pattern)
        required.update(path.relative_to(root).as_posix() for path in root.glob(pattern) if path.is_file())
    for directory in ("src/rope_profiler", *_PUBLIC_DIRECTORIES):
        for path in (root / directory).rglob("*"):
            relative = PurePosixPath(path.relative_to(root).as_posix())
            if path.is_file() and _authored(relative):
                required.add(str(relative))
    return required


def _match_content(root: Path, relative: str, content: bytes, *, origin: str) -> dict[str, Any]:
    relative_path = _safe_member(relative)
    path = root.joinpath(*relative_path.parts)
    if not path.is_file():
        raise ReleaseBundleError(f"{origin} input is absent from the current project: {relative}")
    fingerprint = _sha_file(path)
    if fingerprint != _sha_bytes(content):
        raise ReleaseBundleError(f"{origin} source bytes differ from the current project: {relative}")
    return fingerprint


def _source_identity(root: Path, wheel: Path, sdist: Path) -> dict[str, dict[str, Any]]:
    required = _required_inputs(root)
    package_inputs = {name for name in required if name.startswith("src/rope_profiler/")}
    wheel_package_inputs: set[str] = set()
    source_files: dict[str, dict[str, Any]] = {}
    with zipfile.ZipFile(wheel) as archive:
        seen: set[str] = set()
        for member in archive.infolist():
            if member.is_dir():
                continue
            path = _safe_member(member.filename)
            name = str(path)
            if name in seen:
                raise ReleaseBundleError(f"wheel contains a duplicate file: {name}")
            seen.add(name)
            if name.startswith("rope_profiler/"):
                relative = "src/" + name
                if not _authored(path):
                    raise ReleaseBundleError(f"wheel includes generated bytecode/cache: {name}")
                wheel_package_inputs.add(relative)
                source_files[relative] = _match_content(root, relative, archive.read(member), origin="wheel")
            elif ".dist-info/licenses/" in name:
                relative = name.split(".dist-info/licenses/", 1)[1]
                source_files[relative] = _match_content(root, relative, archive.read(member), origin="wheel license")
        if wheel_package_inputs != package_inputs:
            missing = sorted(package_inputs - wheel_package_inputs)
            extra = sorted(wheel_package_inputs - package_inputs)
            raise ReleaseBundleError(f"wheel source file set differs from the current project; missing={missing}, extra={extra}")

    sdist_inputs: set[str] = set()
    archive_roots: set[str] = set()
    with tarfile.open(sdist, "r:gz") as archive:
        seen = set()
        for member in archive.getmembers():
            if member.isdir():
                continue
            path = _safe_member(member.name)
            if len(path.parts) < 2:
                raise ReleaseBundleError("sdist files must reside under one archive root directory")
            archive_roots.add(path.parts[0])
            relative_path = PurePosixPath(*path.parts[1:])
            relative = str(relative_path)
            if relative in seen or not member.isfile():
                raise ReleaseBundleError(f"sdist contains a duplicate or nonregular file: {relative}")
            seen.add(relative)
            # These files are generated by setuptools, rather than authored inputs.
            if relative == "PKG-INFO" or relative.startswith("src/rope_profiler.egg-info/"):
                continue
            if not _authored(relative_path):
                raise ReleaseBundleError(f"sdist includes generated bytecode/cache: {relative}")
            stream = archive.extractfile(member)
            if stream is None:
                raise ReleaseBundleError(f"cannot read sdist input: {relative}")
            content = stream.read()
            if relative == "setup.cfg" and not (root / relative).exists():
                # Setuptools adds this minimal file to sdist. Any other build
                # configuration must be an explicit, byte-matched local input.
                generated = configparser.ConfigParser(interpolation=None)
                try:
                    generated.read_string(content.decode("utf-8"))
                except (UnicodeDecodeError, configparser.Error) as exc:
                    raise ReleaseBundleError("sdist generated setup.cfg is not the standard setuptools configuration") from exc
                if (generated.defaults() or generated.sections() != ["egg_info"]
                        or dict(generated["egg_info"]) != {"tag_build": "", "tag_date": "0"}):
                    raise ReleaseBundleError("sdist generated setup.cfg has unexpected configuration")
                continue
            fingerprint = _match_content(root, relative, content, origin="sdist")
            if relative in source_files and fingerprint != source_files[relative]:
                raise ReleaseBundleError(f"wheel and sdist source bytes disagree: {relative}")
            source_files[relative] = fingerprint
            sdist_inputs.add(relative)
    if len(archive_roots) != 1:
        raise ReleaseBundleError("sdist must contain exactly one archive root directory")
    missing = sorted(required - sdist_inputs)
    if missing:
        raise ReleaseBundleError(f"sdist is missing current public/build inputs: {missing}")
    return dict(sorted(source_files.items()))


def _metadata_content_identity(root: Path, wheel: Path, sdist: Path) -> None:
    """Keep the published README and dependency declarations in both builds aligned."""
    from packaging.requirements import InvalidRequirement, Requirement
    from packaging.utils import InvalidName, canonicalize_name

    project = check_release.tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    readme = project["readme"]
    readme_path = readme if isinstance(readme, str) else readme["file"]
    expected_readme = (root / readme_path).read_text(encoding="utf-8").rstrip()
    with zipfile.ZipFile(wheel) as archive:
        name = next(name for name in archive.namelist() if name.endswith(".dist-info/METADATA"))
        wheel_metadata = Parser().parsestr(archive.read(name).decode("utf-8"))
    with tarfile.open(sdist, "r:gz") as archive:
        member = next(member for member in archive.getmembers()
                      if member.name.count("/") == 1 and member.name.endswith("/PKG-INFO") and member.isfile())
        stream = archive.extractfile(member)
        if stream is None:
            raise ReleaseBundleError("cannot read sdist metadata payload")
        sdist_metadata = Parser().parsestr(stream.read().decode("utf-8"))
    identities = []
    for kind, metadata in (("wheel", wheel_metadata), ("sdist", sdist_metadata)):
        payload = metadata.get_payload()
        if not isinstance(payload, str) or payload.rstrip() != expected_readme:
            raise ReleaseBundleError(f"{kind} metadata README payload differs from the current project README")
        try:
            requirements = {Requirement(value) for value in metadata.get_all("Requires-Dist", [])}
        except InvalidRequirement as exc:
            raise ReleaseBundleError(f"{kind} metadata has an invalid Requires-Dist declaration") from exc
        try:
            extras = {canonicalize_name(value, validate=True) for value in metadata.get_all("Provides-Extra", [])}
        except InvalidName as exc:
            raise ReleaseBundleError(f"{kind} metadata has an invalid Provides-Extra declaration") from exc
        identities.append((requirements, extras))
    if identities[0][0] != identities[1][0]:
        raise ReleaseBundleError("wheel and sdist Requires-Dist declarations differ")
    if identities[0][1] != identities[1][1]:
        raise ReleaseBundleError("wheel and sdist Provides-Extra declarations differ")


def _expected_manifest(root: Path, artifacts_dir: Path, mode: str) -> dict[str, Any]:
    report = check_release.check_project(root, require_license=mode == "release", dist_dir=artifacts_dir)
    paths = [Path(name) for name in report["artifacts"]]
    wheel = next(path for path in paths if path.suffix == ".whl")
    sdist = next(path for path in paths if path.name.endswith(".tar.gz"))
    from packaging.utils import InvalidSdistFilename, InvalidWheelFilename, parse_sdist_filename, parse_wheel_filename
    from packaging.version import Version
    try:
        wheel_name, wheel_version, _, _ = parse_wheel_filename(wheel.name)
        sdist_name, sdist_version = parse_sdist_filename(sdist.name)
    except (InvalidSdistFilename, InvalidWheelFilename) as exc:
        raise ReleaseBundleError("input artifact filename is not a valid wheel/sdist filename") from exc
    for name, version, artifact in ((wheel_name, wheel_version, wheel), (sdist_name, sdist_version, sdist)):
        if check_release._normalize_name(name) != report["project"] or version != Version(report["version"]):
            raise ReleaseBundleError(f"artifact filename disagrees with source package/version: {artifact.name}")
    artifacts = {
        path.name: {"kind": "wheel" if path.suffix == ".whl" else "sdist", **_sha_file(path)}
        for path in sorted(paths)
    }
    source_files = _source_identity(root, wheel, sdist)
    _metadata_content_identity(root, wheel, sdist)
    if mode == "release":
        with zipfile.ZipFile(wheel) as archive:
            wheel_license_paths = {
                name.split(".dist-info/licenses/", 1)[1]
                for name in archive.namelist() if ".dist-info/licenses/" in name
            }
        missing = set(report["license_files"]) - wheel_license_paths
        if missing:
            raise ReleaseBundleError(f"release wheel is missing required license files: {sorted(missing)}")
    return {
        "schema": SCHEMA,
        "project": report["project"],
        "version": report["version"],
        "mode": mode,
        "hash_algorithm": "sha256",
        "requires_python": report["requires_python"],
        "license": {"verified": report["license_required"], "expression": report["license_expression"],
                    "files": report["license_files"]},
        "artifacts": artifacts,
        "source_files": source_files,
    }


def _manifest_bytes(manifest: dict[str, Any]) -> bytes:
    return (json.dumps(manifest, indent=2, sort_keys=True, allow_nan=False) + "\n").encode("utf-8")


def _sums_bytes(manifest: dict[str, Any]) -> bytes:
    return "".join(f"{details['sha256']}  {filename}\n" for filename, details in sorted(manifest["artifacts"].items())).encode("ascii")


def _check_candidate_contents(output_dir: Path, expected: dict[str, Any]) -> None:
    expected_names = {"manifest.json", "SHA256SUMS", *expected["artifacts"]}
    if not output_dir.is_dir() or {path.name for path in output_dir.iterdir()} != expected_names:
        raise ReleaseBundleError(f"candidate directory conflicts with the expected file set: {output_dir}")
    for path in output_dir.iterdir():
        if path.is_symlink() or not path.is_file():
            raise ReleaseBundleError(f"candidate must contain only regular files: {path.name}")
    if (output_dir / "manifest.json").read_bytes() != _manifest_bytes(expected):
        raise ReleaseBundleError("candidate manifest conflicts with current source, mode, or artifact hashes")
    if (output_dir / "SHA256SUMS").read_bytes() != _sums_bytes(expected):
        raise ReleaseBundleError("candidate SHA256SUMS conflicts with artifact hashes")
    for filename, details in expected["artifacts"].items():
        if _sha_file(output_dir / filename) != {"sha256": details["sha256"], "size": details["size"]}:
            raise ReleaseBundleError(f"candidate artifact bytes conflict with the expected hash: {filename}")


def prepare_release(project_root: Path, *, output_dir: Path, dist_dir: Path | None = None,
                    mode: str = "draft", verify_only: bool = False) -> dict[str, Any]:
    """Return the deterministic manifest for a new, identical, or verified bundle."""
    if mode not in {"draft", "release"}:
        raise ReleaseBundleError("mode must be draft or release")
    root = project_root.resolve()
    output_dir = output_dir.absolute()
    if output_dir.is_symlink():
        raise ReleaseBundleError("candidate output directory must not be a symlink")
    output_dir = output_dir.resolve()
    for directory in ("src/rope_profiler", *_PUBLIC_DIRECTORIES):
        if output_dir == root / directory or root.joinpath(directory) in output_dir.parents:
            raise ReleaseBundleError("candidate output directory must be outside authored build input directories")
    if verify_only:
        if dist_dir is not None:
            raise ReleaseBundleError("verify-only reads artifacts from output-dir; omit dist-dir")
        path = output_dir / "manifest.json"
        if not path.is_file():
            raise ReleaseBundleError("verify-only requires an existing candidate manifest.json")
        stored = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(stored, dict) or stored.get("schema") != SCHEMA or stored.get("mode") != mode:
            raise ReleaseBundleError("candidate manifest schema or mode differs from the requested verification")
        expected = _expected_manifest(root, output_dir, mode)
        _check_candidate_contents(output_dir, expected)
        return expected
    if dist_dir is None:
        raise ReleaseBundleError("preparation requires dist-dir containing one prebuilt wheel and sdist")
    dist_dir = dist_dir.resolve()
    if output_dir == dist_dir:
        raise ReleaseBundleError("output-dir must be separate from the input artifact directory")
    expected = _expected_manifest(root, dist_dir, mode)
    if output_dir.exists():
        _check_candidate_contents(output_dir, expected)
        return expected
    output_dir.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=f".{output_dir.name}-", dir=output_dir.parent))
    try:
        for filename, details in expected["artifacts"].items():
            source = dist_dir / filename
            shutil.copyfile(source, staging / filename)
            fingerprint = {"sha256": details["sha256"], "size": details["size"]}
            if _sha_file(source) != fingerprint or _sha_file(staging / filename) != fingerprint:
                raise ReleaseBundleError(f"input artifact changed during candidate preparation: {filename}")
        (staging / "manifest.json").write_bytes(_manifest_bytes(expected))
        (staging / "SHA256SUMS").write_bytes(_sums_bytes(expected))
        # Recheck the staged bytes against current source before installing it.
        if _expected_manifest(root, staging, mode) != expected:
            raise ReleaseBundleError("source or artifact inputs changed during candidate preparation")
        _check_candidate_contents(staging, expected)
        if output_dir.exists():
            _check_candidate_contents(output_dir, expected)
            return expected
        try:
            staging.rename(output_dir)
        except OSError:
            if not output_dir.exists():
                raise
            _check_candidate_contents(output_dir, expected)
        return expected
    finally:
        if staging.exists():
            shutil.rmtree(staging)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--dist-dir", type=Path)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--mode", choices=("draft", "release"), default="draft")
    parser.add_argument("--verify-only", action="store_true")
    arguments = parser.parse_args()
    try:
        manifest = prepare_release(arguments.project_root, output_dir=arguments.output_dir,
                                   dist_dir=arguments.dist_dir, mode=arguments.mode,
                                   verify_only=arguments.verify_only)
    except (ReleaseBundleError, check_release.ReleaseCheckError, OSError, SyntaxError,
            check_release.tomllib.TOMLDecodeError, json.JSONDecodeError, zipfile.BadZipFile, tarfile.TarError) as exc:
        parser.exit(1, f"Local release candidate failed: {exc}\n")
    print(json.dumps({"output_dir": str(arguments.output_dir.resolve()), "schema": manifest["schema"],
                      "version": manifest["version"], "mode": manifest["mode"],
                      "artifacts": manifest["artifacts"], "source_file_count": len(manifest["source_files"]),
                      "verified_only": arguments.verify_only}, indent=2, allow_nan=False))


if __name__ == "__main__":
    main()
