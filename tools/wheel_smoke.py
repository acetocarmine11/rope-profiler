#!/usr/bin/env python3
"""Exercise an installed wheel from a clean consumer interpreter.

Run from outside the checkout with an isolated interpreter, for example:
    /tmp/consumer/bin/python -I /checkout/tools/wheel_smoke.py
This script deliberately never adds the checkout's src directory to sys.path.
"""
from __future__ import annotations

import argparse
import base64
import csv
import hashlib
import importlib.metadata
import io
import json
from pathlib import Path
import sys


def verify_installed_record(distribution: importlib.metadata.Distribution) -> int:
    """Check the bytes and sizes of hashed files in the installed RECORD.

    The RECORD itself and generated bytecode may legally omit their hashes;
    these entries are skipped. Other files must declare both a hash and size.
    This verifies local installation integrity, not the artifact's authorship.
    """
    # Python 3.12's Distribution.files drops missing entries; reading RECORD
    # directly ensures deletions are still detected in every supported Python.
    record_text = distribution.read_text("RECORD")
    if not record_text:
        raise AssertionError("installed distribution RECORD is empty or missing")
    verified = 0
    rows = list(csv.reader(io.StringIO(record_text)))
    if not rows:
        raise AssertionError("installed distribution RECORD is empty or missing")
    for row in rows:
        if len(row) != 3 or not row[0]:
            raise AssertionError("installed RECORD contains a malformed row")
        entry, hash_field, size_field = row
        path = Path(distribution.locate_file(entry))
        is_record = path.name == "RECORD" and path.parent.name.endswith(".dist-info")
        if not hash_field:
            if is_record or path.suffix == ".pyc":
                continue
            raise AssertionError(f"installed RECORD omits the hash for {entry}")
        if not size_field:
            raise AssertionError(f"installed RECORD omits the size for {entry}")
        try:
            recorded_size = int(size_field)
        except ValueError as exc:
            raise AssertionError(f"installed RECORD declares an invalid size for {entry}") from exc
        if recorded_size < 0:
            raise AssertionError(f"installed RECORD declares an invalid size for {entry}")
        hash_mode, separator, hash_value = hash_field.partition("=")
        if not separator or not hash_mode or not hash_value:
            raise AssertionError(f"installed RECORD declares a malformed hash for {entry}")
        if not path.is_file():
            raise AssertionError(f"installed RECORD file is missing: {entry}")
        try:
            digest = hashlib.new(hash_mode)
        except ValueError as exc:
            raise AssertionError(f"installed RECORD uses an unsupported hash algorithm for {entry}: {hash_mode}") from exc
        size = 0
        try:
            with path.open("rb") as stream:
                for block in iter(lambda: stream.read(1024 * 1024), b""):
                    digest.update(block)
                    size += len(block)
        except OSError as exc:
            raise AssertionError(f"installed RECORD file cannot be read: {entry}") from exc
        if size != recorded_size:
            raise AssertionError(f"installed RECORD size mismatch for {entry}: {size} != {recorded_size}")
        actual_hash = base64.urlsafe_b64encode(digest.digest()).rstrip(b"=").decode("ascii")
        if actual_hash != hash_value:
            raise AssertionError(f"installed RECORD hash mismatch for {entry}")
        verified += 1
    return verified


def smoke(expected_version: str | None = None) -> dict[str, object]:
    forbidden = {"transformers", "wandb"}
    loaded = forbidden.intersection(sys.modules)
    if loaded:
        raise AssertionError(f"consumer interpreter already imported optional dependencies: {sorted(loaded)}")

    distribution = importlib.metadata.distribution("rope-profiler")
    verified_files = verify_installed_record(distribution)

    import rope_profiler
    import torch

    loaded = forbidden.intersection(sys.modules)
    if loaded:
        raise AssertionError(f"core import loaded optional dependencies: {sorted(loaded)}")
    package_file = Path(rope_profiler.__file__).resolve()
    wheel_files = distribution.files or []
    recorded_init = [item for item in wheel_files if str(item) == "rope_profiler/__init__.py"]
    if len(recorded_init) != 1 or Path(distribution.locate_file(recorded_init[0])).resolve() != package_file:
        raise AssertionError("rope_profiler must be imported from the installed wheel's RECORD, not an editable/source checkout")
    if package_file.parent.parent.name == "src":
        raise AssertionError(f"source checkout masks the installed wheel: {package_file}")
    if rope_profiler.__version__ != distribution.version:
        raise AssertionError(f"package version {rope_profiler.__version__!r} differs from wheel metadata {distribution.version!r}")
    if expected_version is not None and distribution.version != expected_version:
        raise AssertionError(f"installed version {distribution.version!r} differs from expected version {expected_version!r}")

    config = rope_profiler.MonitorConfig(
        queries=2, keys=3, distance_samples=8, seed=7, max_examples=2,
        layers=(0,), heads={0: (0, 1)}, cache_entries=2,
    )
    restored = rope_profiler.MonitorConfig.from_dict(json.loads(json.dumps(config.to_dict())))
    if restored != config:
        raise AssertionError("configuration JSON round trip changed the configuration")
    generator = torch.Generator(device="cpu").manual_seed(config.seed)
    q = torch.randn(2, 2, 8, generator=generator)
    k = torch.randn(1, 3, 8, generator=generator)
    result = rope_profiler.score_activations(
        q, k, [0, 0], [[0, 0], [0, 1], [1, 2]],
        [[0, 0, 1], [1, 1, 2]], [1.0, 0.1, 0.01, 0.001], 16,
        distance_samples=config.distance_samples, seed=config.seed,
        dtype=config.score_dtype,
    )
    if not bool(torch.isfinite(result.semantic_by_head).all()):
        raise AssertionError("semantic smoke score contains an undefined value")
    if not bool(((result.semantic_by_head >= 0) & (result.semantic_by_head <= 1)).all()):
        raise AssertionError("semantic smoke score is outside [0, 1]")
    if not bool((torch.isfinite(result.positional_by_head) & (result.positional_by_head >= 0)).all()):
        raise AssertionError("positional smoke score is undefined or negative")
    if int(result.semantic_valid_triplets) != 4 or int(result.positional_valid_pairs) != 6:
        raise AssertionError("smoke score did not process all selected cells and heads")
    if int(result.invalid_cells) != 0:
        raise AssertionError("smoke score reported invalid cells")
    if forbidden.intersection(sys.modules):
        raise AssertionError("core scoring imported an optional dependency")
    preset_counts = {name: len(rope_profiler.get_head_preset(name).ranked_heads)
                     for name in rope_profiler.list_head_presets()}
    if preset_counts != {"qwen3-8b": 58, "llama-3.1-8b-instruct": 52}:
        raise AssertionError("installed wheel is missing the verified paper head presets")
    if any(name in sys.modules for name in ("matplotlib", "research_tools")):
        raise AssertionError("core preset access imported repository research tools")
    return {
        "version": distribution.version,
        "verified_files": verified_files,
        "package_file": str(package_file),
        "torch_version": torch.__version__,
        "semantic_by_head": result.semantic_by_head.tolist(),
        "positional_by_head": result.positional_by_head.tolist(),
        "semantic_valid_triplets": int(result.semantic_valid_triplets),
        "positional_valid_pairs": int(result.positional_valid_pairs),
        "config_roundtrip": True,
        "paper_preset_counts": preset_counts,
        "optional_dependencies_imported": [],
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--expected-version")
    arguments = parser.parse_args()
    print(json.dumps(smoke(arguments.expected_version), indent=2, allow_nan=False))


if __name__ == "__main__":
    main()
